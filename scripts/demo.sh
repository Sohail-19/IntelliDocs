#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
umask 077

if [[ $# -eq 2 && $1 == down ]]; then
  run="$2"
  if [[ ! "$run" =~ ^data/demo/intellidocs-pilot-[a-z0-9]+$ ]] || [[ ! -f "$run/compose.env" ]]; then
    echo 'Supply the data/demo/intellidocs-pilot-* directory printed by the demo.' >&2
    exit 2
  fi
  LLM_API_KEY='' LLM_BASE_URL='' docker compose --env-file "$run/compose.env" -p "${run##*/}" \
    -f docker-compose.yml -f scripts/demo.compose.yml down --volumes --remove-orphans
  exit
fi
if [[ $# -ne 0 ]]; then
  echo 'Usage: bash scripts/demo.sh [down RUN_DIRECTORY]' >&2
  exit 2
fi

docker info --format '{{.ServerVersion}}' >/dev/null
python_bin="${DEMO_PYTHON:-services/intelligence/.venv/bin/python}"
if [[ -z "${DEMO_PYTHON:-}" && ! -x "$python_bin" ]]; then
  python_bin="$(command -v python3.11 || command -v python3 || true)"
fi
if [[ -z "$python_bin" ]] || ! "$python_bin" -c 'import sys; sys.exit(sys.version_info < (3, 11))'; then
  echo 'The demo requires Python 3.11 or later. Set DEMO_PYTHON to its executable.' >&2
  exit 2
fi
mkdir -p data/demo
run="data/demo/intellidocs-pilot-$("$python_bin" -c 'import secrets; print(secrets.token_hex(5))')"
mkdir "$run"
mode="${DEMO_LLM_MODE:-fixture}"
"$python_bin" -m scripts.seed_demo init "$run" --mode "$mode"

# Generated by seed_demo; values written here have been validated or generated locally.
set -a
# shellcheck disable=SC1090
source "$run/compose.env"
set +a
compose=(docker compose --env-file "$run/compose.env" -p "${run##*/}" \
  -f docker-compose.yml -f scripts/demo.compose.yml)
if [[ "$mode" == fixture ]]; then
  export LLM_API_KEY='' LLM_BASE_URL=''
  compose+=(-f e2e/compose.yml)
else
  export LLM_BASE_URL="${LLM_BASE_URL:-}"
fi

echo "Pilot directory $run"
echo "Stop and remove this pilot with: bash scripts/demo.sh down $run"
"${compose[@]}" up -d --wait --wait-timeout 120 postgres
"${compose[@]}" run --rm --build migrate
"${compose[@]}" up -d --build --wait --wait-timeout 240
"$python_bin" -m scripts.seed_demo seed "$run"
